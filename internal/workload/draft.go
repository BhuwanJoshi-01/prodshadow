package workload

import (
	"fmt"
	"io"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/BhuwanJoshi-01/Open-Source-1/internal/pglock"
	"github.com/BhuwanJoshi-01/Open-Source-1/internal/sqlinspect"
)

// StatRecord is one row of a pg_stat_statements export: a normalised query
// with $n placeholders and how often it ran.
type StatRecord struct {
	Query string
	Calls int64
}

// DraftOptions control which statements become scenarios.
type DraftOptions struct {
	// Top keeps the N most frequent statements (0 keeps all).
	Top int
	// Table keeps only statements that mention this relation.
	Table string
	// Name is the workload name.
	Name string
}

// Draft is a workload file generated from statistics, plus the statements
// that were left out and why.
type Draft struct {
	Name      string
	Scenarios []DraftScenario
	Skipped   []string
}

// DraftScenario is one generated scenario.
type DraftScenario struct {
	ID     string
	Mode   string
	Weight int64
	SQL    string
	Params int
}

// DraftFromStats turns pg_stat_statements rows into scenarios: weights are
// the call counts, modes follow the statement type, and every placeholder
// gets a generator to be refined by hand. Statements a workload cannot run
// (DDL, utility commands, transaction control) are skipped.
func DraftFromStats(records []StatRecord, opts DraftOptions) Draft {
	sorted := append([]StatRecord(nil), records...)
	sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].Calls > sorted[j].Calls })
	d := Draft{Name: opts.Name}
	ids := map[string]int{}
	for _, r := range sorted {
		q := strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(r.Query), ";"))
		if q == "" || r.Calls <= 0 {
			continue
		}
		if opts.Table != "" && !mentions(q, opts.Table) {
			continue
		}
		st, err := sqlinspect.ParseOne(q)
		if err == nil {
			err = st.RequireDML()
		}
		if err != nil {
			d.Skipped = append(d.Skipped, fmt.Sprintf("%s (%v)", oneLine(q, 80), err))
			continue
		}
		if opts.Top > 0 && len(d.Scenarios) >= opts.Top {
			break
		}
		// Only plain reads count as reads: SELECT ... FOR UPDATE and
		// SELECTs with data-modifying WITH clauses take row locks.
		mode := "write"
		if st.Kind == sqlinspect.KindSelect && st.StrongestLock() <= pglock.AccessShare {
			mode = "read"
		}
		d.Scenarios = append(d.Scenarios, DraftScenario{ID: scenarioID(st, ids), Mode: mode, Weight: r.Calls, SQL: oneLine(q, 0), Params: st.MaxParam()})
	}
	return d
}

var wordRe = regexp.MustCompile(`[^a-z0-9]+`)

// scenarioID names a scenario after its verb and first table, e.g.
// select_orders, select_orders_2.
func scenarioID(st *sqlinspect.Statement, seen map[string]int) string {
	verb := strings.ToLower(strings.Fields(st.Tag)[0])
	base := verb
	if t := st.Tables(); len(t) > 0 {
		base += "_" + strings.Trim(wordRe.ReplaceAllString(strings.ToLower(lastName(t[0])), "_"), "_")
	}
	if len(base) > 56 {
		base = base[:56]
	}
	seen[base]++
	if n := seen[base]; n > 1 {
		return base + "_" + strconv.Itoa(n)
	}
	return base
}

func lastName(qualified string) string {
	if i := strings.LastIndex(qualified, "."); i >= 0 {
		return qualified[i+1:]
	}
	return qualified
}

func mentions(query, table string) bool {
	re := regexp.MustCompile(`(?i)(^|[^a-z0-9_])` + regexp.QuoteMeta(table) + `($|[^a-z0-9_])`)
	return re.MatchString(query)
}

// oneLine collapses whitespace and, with limit > 0, shortens the text.
func oneLine(s string, limit int) string {
	s = strings.Join(strings.Fields(s), " ")
	if limit > 0 && len(s) > limit {
		s = s[:limit-1] + "…"
	}
	return s
}

// Write renders the draft as a commented workload file.
func (d Draft) Write(w io.Writer) error {
	var b strings.Builder
	b.WriteString("# Draft generated by prodshadow draft-workload from pg_stat_statements.\n")
	b.WriteString("# Review every scenario: replace the placeholder generators with ranges\n")
	b.WriteString("# that match your data, and add background sessions for long\n")
	b.WriteString("# transactions (see docs/guides/modelling-traffic.md).\n")
	b.WriteString("version: 1\n")
	if d.Name != "" {
		fmt.Fprintf(&b, "name: %s\n", strconv.Quote(d.Name))
	}
	b.WriteString("scenarios:\n")
	for _, s := range d.Scenarios {
		fmt.Fprintf(&b, "  - id: %s\n    weight: %d\n    mode: %s\n    sql: %s\n", s.ID, s.Weight, s.Mode, strconv.Quote(s.SQL))
		if s.Params > 0 {
			b.WriteString("    parameters:\n")
			for i := 1; i <= s.Params; i++ {
				fmt.Fprintf(&b, "      - {generator: int_range, min: 1, max: 1000}  # TODO: $%d\n", i)
			}
		}
	}
	if len(d.Scenarios) == 0 {
		b.WriteString("  [] # no statement could be used as a scenario\n")
	}
	if len(d.Skipped) > 0 {
		b.WriteString("\n# Skipped (not runnable as workload scenarios):\n")
		for _, s := range d.Skipped {
			fmt.Fprintf(&b, "#   %s\n", s)
		}
	}
	_, err := io.WriteString(w, b.String())
	return err
}

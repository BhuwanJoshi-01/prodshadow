#!/usr/bin/env bash
# Prints the Homebrew formula for a release from its SHA256SUMS file.
#
#   packaging/homebrew/formula.sh v0.1.0 dist/SHA256SUMS > prodshadow.rb
#
# The release workflow attaches the result to the draft release. To publish
# it, copy it to Formula/prodshadow.rb in the tap repository
# (github.com/BhuwanJoshi-01/homebrew-tap); see RELEASING.md.
set -euo pipefail

tag=${1:?usage: formula.sh <tag> <SHA256SUMS>}
sums=${2:?usage: formula.sh <tag> <SHA256SUMS>}
version=${tag#v}
base="https://github.com/BhuwanJoshi-01/prodshadow/releases/download/$tag"

sum() {
  local file="prodshadow_${version}_$1.tar.gz" value
  value=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  if [[ ! "$value" =~ ^[0-9a-f]{64}$ ]]; then
    echo "formula.sh: no SHA-256 for $file in $sums" >&2
    exit 1
  fi
  printf '%s' "$value"
}

# Assignments, so a missing checksum stops the script (set -e) before
# anything is printed.
darwin_arm64=$(sum darwin_arm64)
darwin_amd64=$(sum darwin_amd64)
linux_arm64=$(sum linux_arm64)
linux_amd64=$(sum linux_amd64)

cat <<RUBY
# Generated by packaging/homebrew/formula.sh for $tag.
class Prodshadow < Formula
  desc "Rehearse PostgreSQL migrations under load in a disposable database"
  homepage "https://bhuwanjoshi-01.github.io/prodshadow/"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/prodshadow_${version}_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/prodshadow_${version}_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/prodshadow_${version}_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/prodshadow_${version}_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "prodshadow"
    generate_completions_from_executable(bin/"prodshadow", "completion")
  end

  def caveats
    <<~EOS
      prodshadow verify runs PostgreSQL in a container: it needs Docker or
      Podman. inspect and plan work without one.
    EOS
  end

  test do
    assert_match "prodshadow #{version}", shell_output("#{bin}/prodshadow version")
    (testpath/"m.sql").write "ALTER TABLE t ADD COLUMN c int;"
    assert_match "ACCESS EXCLUSIVE", shell_output("#{bin}/prodshadow inspect --migration m.sql")
  end
end
RUBY
